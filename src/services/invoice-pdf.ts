export function normalizeInvoicePdfOptions(
  layout: string | null | undefined,
  language: string | null | undefined,
): InvoicePdfOptions {
  return {
    layout: layout === "branded" || layout === "compact" ? layout : "classic",
    language: language === "es" ? "es" : "en",
  };
}

const amount = (value: string) => {
  const [whole, fraction] = D(value).toFixed(2).split(".");
  const negative = whole.startsWith("-");
  const digits = negative ? whole.slice(1) : whole;
  const prefix = digits.slice(0, -3).replace(/\B(?=(?:\d{2})+(?!\d))/g, ",");
  return `${negative ? "-" : ""}${prefix ? `${prefix},` : ""}${digits.slice(-3)}.${fraction}`;
};

const lastTableY = (doc: jsPDF) => (doc as jsPDF & { lastAutoTable: { finalY: number } }).lastAutoTable.finalY;

function renderClassic(doc: jsPDF, data: InvoicePdfData, language: InvoicePdfLanguage) {
  const { company, invoice, party } = data;
  const labels = LABELS[language];
  const width = doc.internal.pageSize.getWidth();
  const currency = company.currency;
  doc.setFillColor(10, 19, 37);
  doc.rect(0, 0, width, 70, "F");
  doc.setTextColor(255);
  doc.setFontSize(18);
  doc.text(invoice.kind === "sales" ? labels.taxInvoice : labels.purchaseBill, 36, 42);
  doc.setFontSize(9);
  doc.text(company.name, width - 36, 30, { align: "right" });
  doc.text(`${labels.gstin} ${company.gstin ?? "—"}`, width - 36, 44, { align: "right" });
  doc.setTextColor(30);
  doc.setFontSize(10);
  doc.text(`${labels.invoiceNumber} ${invoice.number}`, 36, 100);
  doc.text(`${labels.date} ${invoice.date}`, 36, 114);
  doc.text(`${labels.dueDate} ${invoice.dueDate}`, 36, 128);
  doc.text(`${labels.placeOfSupply} ${invoice.placeOfSupply}`, 36, 142);
  doc.setFont("helvetica", "bold");
  doc.text(invoice.kind === "sales" ? labels.billTo : labels.supplier, 330, 100);
  doc.setFont("helvetica", "normal");
  doc.text(party.name, 330, 114);
  doc.text(`${labels.gstin} ${party.gstin ?? "Unregistered"}`, 330, 128);
  if (party.pan) doc.text(`${labels.pan} ${party.pan}`, 330, 142);
  autoTable(doc, {
    startY: 165,
    head: [["#", labels.description, "HSN/SAC", labels.quantity, `${labels.rate} (${currency})`, "GST %", `${labels.amount} (${currency})`]],
    body: invoice.items.map((item, index) => [index + 1, item.description, item.hsn, item.qty, amount(item.rate), item.gstRate, amount(r2(D(item.rate).mul(item.qty)).toFixed(2))]),
    styles: { fontSize: 9 },
    headStyles: { fillColor: [14, 26, 48] },
    columnStyles: { 3: { halign: "right" }, 4: { halign: "right" }, 5: { halign: "right" }, 6: { halign: "right" } },
  });
  const y = lastTableY(doc) + 16;
  const totals: [string, string][] = [
    [labels.taxable, amount(invoice.taxable)],
    ...(D(invoice.cgst).gt(0) ? [["CGST", amount(invoice.cgst)], ["SGST", amount(invoice.sgst)]] as [string, string][] : []),
    ...(D(invoice.igst).gt(0) ? [["IGST", amount(invoice.igst)]] as [string, string][] : []),
    [labels.total, amount(invoice.total)],
    [labels.paid, amount(invoice.paid)],
    [labels.balance, amount(D(invoice.total).minus(invoice.paid).toFixed(2))],
  ];
  totals.forEach(([label, value], index) => {
    doc.setFont("helvetica", index === totals.length - 1 || label === labels.total ? "bold" : "normal");
    doc.text(label, 380, y + index * 14);
    doc.text(`${currency} ${value}`, width - 36, y + index * 14, { align: "right" });
  });
  if (invoice.notes) {
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.text(`${labels.notes} ${invoice.notes}`, 36, y + 10, { maxWidth: 300 });
  }
  doc.setFontSize(7);
  doc.setTextColor(120);
  doc.text(labels.computerGenerated, 36, 810);
}

function renderAlternative(doc: jsPDF, data: InvoicePdfData, options: InvoicePdfOptions) {
  const { company, invoice, party } = data;
  const labels = LABELS[options.language];
  const compact = options.layout === "compact";
  const width = doc.internal.pageSize.getWidth();
  const rightEdge = width - 36;
  const columnWidth = width - 330;
  const small = compact ? 7 : 8;
  const lineHeight = compact ? 9 : 10;
  const stateName = STATES.find(([code]) => code === company.stateCode)?.[1];
  const profile = [
    company.name,
    company.address,
    company.gstin && `${labels.gstin} ${company.gstin}`,
    company.pan && `${labels.pan} ${company.pan}`,
    `${labels.companyState} ${company.stateCode}${stateName ? ` - ${stateName}` : ""}`,
    `${labels.currency} ${company.currency}`,
  ].filter((line): line is string => Boolean(line));
  const profileLines = profile.flatMap((line) => doc.splitTextToSize(line, columnWidth));
  const headerHeight = Math.max(compact ? 100 : 112, 28 + profileLines.length * lineHeight + 16);
  const title = invoice.kind === "sales" ? labels.taxInvoice : labels.purchaseBill;
  const invoiceInfo = [
    `${labels.invoiceNumber} ${invoice.number}`,
    `${labels.date} ${invoice.date}`,
    `${labels.dueDate} ${invoice.dueDate}`,
    `${labels.placeOfSupply} ${invoice.placeOfSupply}`,
  ];

  doc.setFillColor(...(compact ? [30, 48, 71] as [number, number, number] : [10, 19, 37] as [number, number, number]));
  doc.rect(0, 0, width, headerHeight, "F");
  doc.setFillColor(16, 185, 129);
  doc.rect(0, headerHeight - 4, width, 4, "F");
  doc.setTextColor(255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(compact ? 15 : 18);
  doc.text(title, 36, 30);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(small);
  doc.text(invoiceInfo, 36, compact ? 47 : 52, { lineHeightFactor: compact ? 1.15 : 1.3 });
  doc.setFont("helvetica", "bold");
  doc.setFontSize(compact ? 8 : 9);
  doc.text(profileLines[0] ?? "", rightEdge, 22, { align: "right" });
  doc.setFont("helvetica", "normal");
  doc.setFontSize(small);
  if (profileLines.length > 1) {
    doc.text(profileLines.slice(1), rightEdge, compact ? 34 : 37, { align: "right", lineHeightFactor: compact ? 1.15 : 1.2 });
  }

  const detailsY = headerHeight + (compact ? 14 : 18);
  doc.setTextColor(30);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(small + 1);
  doc.text(invoice.kind === "sales" ? labels.billTo : labels.supplier, 36, detailsY);
  doc.text(labels.placeOfSupply.replace(/:$/, ""), width / 2 + 10, detailsY);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(small);
  const partyLines = [party.name, `${labels.gstin} ${party.gstin ?? "Unregistered"}`, ...(party.pan ? [`${labels.pan} ${party.pan}`] : [])];
  doc.text(doc.splitTextToSize(partyLines.join("\n"), width / 2 - 60), 36, detailsY + 13, { lineHeightFactor: 1.2 });
  doc.text(doc.splitTextToSize(invoice.placeOfSupply, width / 2 - 60), width / 2 + 10, detailsY + 13);

  const startY = detailsY + (compact ? 48 : 56);
  autoTable(doc, {
    startY,
    head: [["#", labels.description, "HSN/SAC", labels.quantity, `${labels.rate} (${company.currency})`, "GST %", `${labels.amount} (${company.currency})`]],
    body: invoice.items.map((item, index) => [index + 1, item.description, item.hsn, item.qty, amount(item.rate), item.gstRate, amount(r2(D(item.rate).mul(item.qty)).toFixed(2))]),
    styles: { fontSize: compact ? 7 : 8, cellPadding: compact ? 3 : 4 },
    headStyles: { fillColor: compact ? [30, 48, 71] : [10, 19, 37] },
    columnStyles: { 3: { halign: "right" }, 4: { halign: "right" }, 5: { halign: "right" }, 6: { halign: "right" } },
  });
  let totalsY = lastTableY(doc) + (compact ? 12 : 16);
  const totals: [string, string][] = [
    [labels.taxable, amount(invoice.taxable)],
    ...(D(invoice.cgst).gt(0) ? [["CGST", amount(invoice.cgst)], ["SGST", amount(invoice.sgst)]] as [string, string][] : []),
    ...(D(invoice.igst).gt(0) ? [["IGST", amount(invoice.igst)]] as [string, string][] : []),
    [labels.total, amount(invoice.total)],
    [labels.paid, amount(invoice.paid)],
    [labels.balance, amount(D(invoice.total).minus(invoice.paid).toFixed(2))],
  ];
  if (totalsY + totals.length * 14 > 770) {
    doc.addPage();
    totalsY = 44;
  }
  totals.forEach(([label, value], index) => {
    doc.setFont("helvetica", index === totals.length - 1 || label === labels.total ? "bold" : "normal");
    doc.setFontSize(small);
    doc.text(label, width - 210, totalsY + index * 14);
    doc.text(`${company.currency} ${value}`, rightEdge, totalsY + index * 14, { align: "right" });
  });
  if (invoice.notes) {
    const notesY = totalsY + totals.length * 14 + 10;
    if (notesY > 780) doc.addPage();
    doc.setFont("helvetica", "normal");
    doc.setFontSize(small);
    doc.text(`${labels.notes} ${invoice.notes}`, 36, notesY > 780 ? 44 : notesY, { maxWidth: width - 72 });
  }
  for (let page = 1; page <= doc.getNumberOfPages(); page++) {
    doc.setPage(page);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(7);
    doc.setTextColor(120);
    doc.text(labels.computerGenerated, 36, 810, { maxWidth: width - 72 });
  }
}

export function createInvoicePdf(data: InvoicePdfData, options: InvoicePdfOptions = { layout: "classic", language: "en" }) {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  if (options.layout === "classic") renderClassic(doc, data, options.language);
  else renderAlternative(doc, data, options);
  return new Uint8Array(doc.output("arraybuffer"));
}
